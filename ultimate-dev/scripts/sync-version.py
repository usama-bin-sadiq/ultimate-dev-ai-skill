#!/usr/bin/env python3
"""Synchronize versioned runtime configuration with the canonical VERSION file."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VERSION_FILE = ROOT.parent / "VERSION"
CONFIG_FILES = (
    ROOT / "config" / "agent_registry.yaml",
    ROOT / "config" / "capability-index.yaml",
    ROOT / "config" / "context_budgets.yaml",
    ROOT / "config" / "models.yaml",
    ROOT / "config" / "permissions.yaml",
    ROOT / "config" / "security.yaml",
    ROOT / "config" / "workflow.yaml",
)
# config/agent-catalog.yaml is deliberately absent: it is regenerated by
# generate-agent-catalog.py during a release and writes an unquoted version, so
# including it here would report permanent drift.
#
# SKILL.md carries a version frontmatter field that validate-consistency.py
# checks, and it was missing from this list. Every automated release therefore
# bumped VERSION and then failed validation with "SKILL.md version != <new>",
# which is why no release succeeded after v3.0.2. Keep this list aligned with the
# version checks in validate-consistency.py.
FRONTMATTER_FILES = (
    ROOT / "AGENT.md",
    ROOT / "AGENTS.md",
    ROOT / "CLAUDE.md",
    ROOT / "SKILL.md",
)
README_FILE = ROOT / "README.md"
SEMVER_RE = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+$")
VERSION_LINE_RE = re.compile(r"^version\s*:")


class SyncVersionError(ValueError):
    """The canonical version or a managed config file is invalid."""


def read_version(path: Path = VERSION_FILE) -> str:
    if not path.is_file():
        raise SyncVersionError(f"canonical VERSION is missing: {path}")
    value = path.read_text(encoding="utf-8").strip()
    if not SEMVER_RE.fullmatch(value):
        raise SyncVersionError(f"canonical VERSION is not semantic: {value}")
    return value


def sync_text(text: str, version: str, *, label: str = "config") -> str:
    if not SEMVER_RE.fullmatch(version):
        raise SyncVersionError(f"version is not semantic: {version}")
    lines = text.splitlines(keepends=True)
    matches = [index for index, line in enumerate(lines) if VERSION_LINE_RE.match(line)]
    if len(matches) != 1:
        raise SyncVersionError(f"{label}: expected exactly one top-level version line")
    index = matches[0]
    line = lines[index]
    newline = "\n" if line.endswith("\n") else ""
    body = line[:-1] if newline else line
    comment = ""
    comment_match = re.search(r"\s+#.*$", body)
    if comment_match:
        comment = comment_match.group(0)
    lines[index] = f'version: "{version}"{comment}{newline}'
    return "".join(lines)


def sync_file(path: Path, version: str, *, check: bool = False) -> bool:
    if not path.is_file():
        raise SyncVersionError(f"managed config is missing: {path}")
    original = path.read_text(encoding="utf-8")
    updated = sync_text(original, version, label=str(path))
    changed = updated != original
    if changed and not check:
        path.write_text(updated, encoding="utf-8")
    return changed


HEADING_RE = re.compile(r"^(#\s*Ultimate-Dev\s+)\d+\.\d+\.\d+(?=[ \t]|$)", re.MULTILINE)


def sync_readme(text: str, version: str) -> str:
    """Update a '# Ultimate-Dev X.Y.Z' heading, preserving any trailing title text.

    README.md uses a bare version heading while SKILL.md appends a subtitle
    ("# Ultimate-Dev 3.0.2 — Prompt-First Core (MANDATORY)"). Both must move
    with VERSION or a release leaves a stale version in a visible title.
    """
    if not SEMVER_RE.fullmatch(version):
        raise SyncVersionError(f"version is not semantic: {version}")
    updated, count = HEADING_RE.subn(rf"\g<1>{version}", text, count=1)
    if count != 1:
        raise SyncVersionError(f"expected one '# Ultimate-Dev X.Y.Z' heading, found {count}")
    return updated


def sync_text_file(path: Path, version: str, *, check: bool = False) -> bool:
    """Sync one managed file, dispatching on its role rather than its identity.

    Dispatching on membership of a module-level tuple made the function
    impossible to exercise against a copy of the file, which is how the missing
    SKILL.md entry went unnoticed.
    """
    if not path.is_file():
        raise SyncVersionError(f"managed file is missing: {path}")
    original = path.read_text(encoding="utf-8")
    if path.name == README_FILE.name:
        updated = sync_readme(original, version)
    else:
        updated = sync_text(original, version, label=str(path))
        if HEADING_RE.search(updated):
            updated = sync_readme(updated, version)
    changed = updated != original
    if changed and not check:
        path.write_text(updated, encoding="utf-8")
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if managed config versions differ")
    args = parser.parse_args(argv)
    try:
        version = read_version()
        changed = [str(path) for path in CONFIG_FILES if sync_file(path, version, check=args.check)]
        changed.extend(
            str(path)
            for path in (*FRONTMATTER_FILES, README_FILE)
            if sync_text_file(path, version, check=args.check)
        )
    except (OSError, SyncVersionError) as exc:
        print(f"sync-version: {exc}", file=sys.stderr)
        return 1
    if args.check and changed:
        for path in changed:
            print(f"sync-version: out of sync: {path} (expected {version})", file=sys.stderr)
        return 1
    if changed:
        print(f"sync-version: synchronized {len(changed)} config file(s) to {version}")
    else:
        print(f"sync-version: already synchronized to {version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
