PAIR_FLAG = re.compile(r"\.bam$", re.IGNORECASE)
# Guarded against a filename: the library layout is declared, never inferred.
LAYOUT_NOTE = (
    "Library layout was NOT passed on the command line, so this script assumes "
    "SINGLE-END. If the library is paired-end, regenerate it with --paired-end, "
    "or check `samtools view -c -f 1 input.bam > 0` before trusting the QC steps."
)


def split_bams(value: str | None) -> list[str]:
    """Accept space-separated names, or a comma-separated list, and clean them up."""
    if not value:
        return []
    parts = re.split(r"[\s,]+", value.strip())
    return [part for part in parts if part]


def guess_prefix(bams: list[str]) -> str:
    """A short label for outputs, taken from the first BAM's stem."""
    if not bams:
        return "sample"
    stem = os.path.basename(bams[0])
    for suffix in (".bam", ".sorted", ".filtered", ".dedup"):
        if stem.endswith(suffix):
            stem = stem[: -len(suffix)]
    return stem or "sample"


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Generate a runnable bash script for a standard deepTools workflow.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument(
        "workflow", nargs="?", choices=sorted(WORKFLOWS),
        help="which workflow to generate",
    )
    parser.add_argument("-o", "--output", default=None, help="write the script here; default stdout")
    parser.add_argument("--list", action="store_true", help="list the available workflows and exit")
    parser.add_argument("--input-bam", default=None, help="the input or control BAM")
    parser.add_argument("--chip-bams", default=None, help="one or more ChIP BAMs, space-separated")
    parser.add_argument("--bed", default=None, help="BED regions: peaks, or genes for RNA-seq")
    parser.add_argument("--genome-size", default=None,
                        help="effective genome size; a bare build name is looked up")
    parser.add_argument("--threads", type=int, default=os.cpu_count() or 4,
                        help="value for --numberOfProcessors")
    parser.add_argument("--bin-size", type=int, default=50, help="bin size in bp")
    parser.add_argument("--flank", type=int, default=3000, help="flanking region in bp")
    parser.add_argument("--strand", choices=("forward", "reverse"), default="forward",
                        help="RNA library orientation; confirm it before trusting strand labels")
    parser.add_argument("--paired-end", dest="paired_end", action="store_true", default=None,
                        help="the library is paired-end (default is single-end, declared not guessed)")
    parser.add_argument("--single-end", dest="paired_end", action="store_false",
                        help="the library is single-end")
    parser.add_argument("--outdir", default="deeptools_out", help="output directory in the script")
    return parser


def list_workflows() -> None:
    print("available workflows:")
    for name in sorted(WORKFLOWS):
        spec = WORKFLOWS[name]
        required = ", ".join(f"--{field.replace('_', '-')}" for field in spec["required"])
        print(f"  {name:<18} {spec['title']}")
        print(f"  {'':<18} required: {required}")
        print(f"  {'':<18} optional: --bed, --genome-size, --threads, --bin-size, "
              "--flank, --strand, --paired-end/--single-end, --outdir")
        print()


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.list or not args.workflow:
        list_workflows()
        return 0

    spec = WORKFLOWS[args.workflow]
    supplied = {
        "input_bam": args.input_bam,
        "chip_bams": args.chip_bams,
        "bed": args.bed,
    }
    missing = [
        field for field in spec["required"] if not supplied.get(field)
    ]
    if missing:
        print(
            f"error: the {args.workflow} workflow needs "
            + ", ".join(f"--{field.replace('_', '-')}" for field in missing),
            file=sys.stderr,
        )
        list_workflows()
        return 1

    genome_size = args.genome_size
    if genome_size is None:
        genome_size = GENOME_SIZES["hg38"]
        genome_note = "defaulted to human GRCh38; set --genome-size for another organism"
    elif str(genome_size).lower() in GENOME_SIZES:
        genome_note = f"{genome_size} resolved to {GENOME_SIZES[str(genome_size).lower()]}"
        genome_size = GENOME_SIZES[str(genome_size).lower()]
    else:
        try:
            genome_size = int(genome_size)
            genome_note = "as supplied"
        except ValueError:
            print(
                f"error: --genome-size must be an integer or one of "
                f"{', '.join(sorted(GENOME_SIZES))}",
                file=sys.stderr,
            )
            return 2

    chip_bams = split_bams(args.chip_bams) or split_bams(args.input_bam)
    input_bams = split_bams(args.input_bam) or chip_bams
    bed_files = split_bams(args.bed)
    # Never guess library layout from a filename: "sample.bam" is what a
    # single-end file is usually called, and a wrong guess silently skips a QC
    # step or runs one that cannot work. Default to single-end and say so in the
    # generated script; --paired-end is the way to override it.
    paired_end = bool(args.paired_end)

    def bash_array(names: list[str]) -> str:
        """A bash array literal; a single empty element keeps the array defined."""
        return " ".join(shlex.quote(name) for name in names) if names else '""'

    values = {
        "outdir": args.outdir,
        "processors": max(1, args.threads),
        "genome_size": genome_size,
        "bin_size": args.bin_size,
        "flank": args.flank,
        "strand": args.strand,
        "prefix": guess_prefix(input_bams),
        "input_bam": args.input_bam,
        "chip_bams": args.chip_bams,
        "chip_bams_joined": " ".join(shlex.quote(name) for name in chip_bams),
        "input_bams_array": bash_array(input_bams),
        "chip_bams_array": bash_array(chip_bams),
        "bed_array": bash_array(bed_files),
        "bed": args.bed,
        "paired_end": "true" if paired_end else "false",
        "title": spec["title"],
    }

    script = HEADER.format(**values) + spec["body"].format(**values) + FOOTER
    notes = [
        f"genome size {genome_size} ({genome_note})",
        f"bin size {args.bin_size} bp",
        f"flank {args.flank} bp",
        f"processors {values['processors']}",
        f"library {'paired-end' if paired_end else 'single-end'}",
        f"RNA strand {args.strand}",
    ]
    script += "\n# parameters in effect: " + "; ".join(notes) + "\n"
    if args.paired_end is None:
        script += f"#\n# {LAYOUT_NOTE}\n"

    if args.output:
        write_script(args.output, script)
        os.chmod(args.output, 0o755)
        print(f"wrote {args.output}", file=sys.stderr)
        print(f"run it with:  chmod +x {args.output} && ./{os.path.basename(args.output)}",
              file=sys.stderr)
    else:
        print(script, end="")
    return 0


def write_script(path: str, text: str) -> None:
    """Write the generated script, creating the parent directory if needed."""
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(text)


if __name__ == "__main__":
    sys.exit(main())
