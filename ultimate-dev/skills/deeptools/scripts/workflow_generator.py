#!/usr/bin/env python3
"""Generate a runnable bash script for a standard deepTools workflow.

What it does
------------
Emits a self-contained ``#!/usr/bin/env bash`` script for one of four documented
workflows, with the parameters you supply already substituted in and every path
quoted. The generated script sets ``set -euo pipefail``, echoes each command
before running it, and writes into one output directory.

Workflows
---------
``chipseq_qc``       fingerprint, coverage, fragment size, read filtering
``chipseq_analysis`` QC, then normalisation, matrices, and heatmaps and profiles
``rnaseq_coverage``  strand-specific coverage, no read extension
``atacseq``          Tn5 correction, fragment filtering, coverage, nucleosome check

Usage
-----
    python scripts/workflow_generator.py --list
    python scripts/workflow_generator.py chipseq_qc -o qc.sh \\
        --input-bam Input.bam --chip-bams "ChIP1.bam ChIP2.bam" \\
        --genome-size 2913022398 --threads 8
    python scripts/workflow_generator.py rnaseq_coverage -o rna.sh \\
        --input-bam rna.bam --strand forward --genome-size 2913022398

Exit codes: 0 written, 1 unknown workflow or missing required input, 2 bad input.

Provenance
----------
Reconstructed from the "scripts/workflow_generator.py" section of this skill's
SKILL.md, which names the four workflows and the flags shown there, and from the
per-assay advice in the same file (extend reads for ChIP, never for RNA, Tn5
shift for ATAC). The emitted command lines are this file's own; the tool names and
flag spellings are deepTools'.
"""

